-- Week 8 additive schema. REVIEW/APPROVAL REQUIRED. No automatic execution.
BEGIN;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS job_title text;
CREATE TABLE IF NOT EXISTS public.governance_drafts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 policy_id bigint REFERENCES public.policies(id),
 base_version_id bigint REFERENCES public.policy_versions(id),
 department_id bigint NOT NULL REFERENCES public.departments(id),
 author_id bigint NOT NULL REFERENCES public.users(id),
 reviewer_id bigint REFERENCES public.users(id),
 title text NOT NULL CHECK(length(trim(title)) BETWEEN 1 AND 200),
 summary text, body text NOT NULL CHECK(length(trim(body)) BETWEEN 1 AND 20000),
 version_no text NOT NULL, category_id bigint REFERENCES public.policy_categories(id),
 effective_date date, review_date date, source_json text,
 status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending_peer_review',
 'pending_final_approval','approved_pending_publication','revisions_requested','rejected','published')),
 revision integer NOT NULL DEFAULT 1,
 peer_approved_by bigint REFERENCES public.users(id),
 final_approved_by bigint REFERENCES public.users(id),
 published_version_id bigint REFERENCES public.policy_versions(id),
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(reviewer_id IS NULL OR reviewer_id <> author_id),
 CHECK(peer_approved_by IS NULL OR peer_approved_by <> author_id),
 CHECK(final_approved_by IS NULL OR (final_approved_by <> author_id AND final_approved_by <> reviewer_id)),
 CHECK(status NOT IN ('pending_final_approval','approved_pending_publication','published') OR peer_approved_by IS NOT NULL),
 CHECK(status NOT IN ('approved_pending_publication','published') OR final_approved_by IS NOT NULL),
 CHECK(status <> 'published' OR published_version_id IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS public.governance_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 draft_id bigint NOT NULL REFERENCES public.governance_drafts(id),
 actor_id bigint NOT NULL REFERENCES public.users(id),
 action text NOT NULL, comment text, snapshot_json text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS governance_queue_idx ON public.governance_drafts(department_id,status,updated_at);
CREATE INDEX IF NOT EXISTS governance_history_idx ON public.governance_events(draft_id,id);
ALTER TABLE public.governance_drafts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.governance_events ENABLE ROW LEVEL SECURITY;
-- All access to working copies goes through the verified backend. No direct-client grants.
REVOKE ALL ON public.governance_drafts,public.governance_events FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public.governance_drafts_id_seq,public.governance_events_id_seq FROM anon,authenticated;
-- Close legacy direct-client policy-write bypasses without removing read privileges.
REVOKE INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER ON public.policies,public.policy_versions FROM anon,authenticated;
CREATE OR REPLACE FUNCTION public.week8_immutable_audit() RETURNS trigger
LANGUAGE plpgsql SET search_path=public AS $$
BEGIN RAISE EXCEPTION 'Governance audit history is append-only'; END $$;
DROP TRIGGER IF EXISTS governance_audit_immutable ON public.governance_events;
CREATE TRIGGER governance_audit_immutable BEFORE UPDATE OR DELETE ON public.governance_events
 FOR EACH ROW EXECUTE FUNCTION public.week8_immutable_audit();
COMMIT;
