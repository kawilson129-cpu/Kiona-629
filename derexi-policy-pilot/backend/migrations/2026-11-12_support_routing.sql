BEGIN;
SELECT pg_advisory_xact_lock(20261112);
CREATE TABLE IF NOT EXISTS public.technical_routes (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 department_id bigint NOT NULL REFERENCES public.departments(id),
 channel text NOT NULL CHECK(channel IN ('it','security')),
 mailbox_key text NOT NULL CHECK(length(mailbox_key) BETWEEN 1 AND 80),
 enabled boolean NOT NULL DEFAULT false,
 revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
 UNIQUE(department_id,channel)
);
CREATE TABLE IF NOT EXISTS public.technical_routing_grants (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES public.users(id),
 department_id bigint NOT NULL REFERENCES public.departments(id),
 UNIQUE(user_id,department_id)
);
CREATE TABLE IF NOT EXISTS public.support_requests (
 id text PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES public.users(id),
 department_id bigint NOT NULL REFERENCES public.departments(id),
 incident_id bigint REFERENCES public.incident_reports(id),
 payload_json text NOT NULL,
 content_hash text NOT NULL,
 route_id integer NOT NULL REFERENCES public.technical_routes(id),
 route_hash text NOT NULL,
 state text NOT NULL DEFAULT 'draft' CHECK(state IN ('draft','queued','disabled','sending','accepted','retryable','unknown','rejected','configuration_error')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 3),
 next_attempt timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS support_requests_owner_created ON public.support_requests(user_id,created_at DESC);
CREATE TABLE IF NOT EXISTS public.support_audit (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id bigint NOT NULL REFERENCES public.users(id),
 request_id text,
 action text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.technical_routes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.technical_routing_grants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.support_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.technical_routes,public.technical_routing_grants,public.support_requests,public.support_audit FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.technical_routes_id_seq,public.technical_routing_grants_id_seq,public.support_audit_id_seq FROM PUBLIC,anon,authenticated;
CREATE OR REPLACE FUNCTION public.support_audit_append_only() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN RAISE EXCEPTION 'Support audit is append-only'; END;
$$;
REVOKE ALL ON FUNCTION public.support_audit_append_only() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS support_audit_no_edit ON public.support_audit;
CREATE TRIGGER support_audit_no_edit BEFORE UPDATE OR DELETE ON public.support_audit FOR EACH ROW EXECUTE FUNCTION public.support_audit_append_only();
