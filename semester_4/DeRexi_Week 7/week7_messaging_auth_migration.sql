-- ============================================================================
-- DeRexi Week 7 — Internal Messaging & Supabase Auth
-- ADDITIVE FORWARD MIGRATION  (PROPOSED — DO NOT APPLY WITHOUT APPROVAL)
--
-- Strategy: reuse clarification_requests / clarification_replies as the thread
-- substrate, link business users to Supabase Auth, add per-user read receipts
-- and internal notifications, and tighten RLS to thread participation.
--
-- Data safety: no existing column is dropped or narrowed and no existing
-- policy/message row is rewritten. The only UPDATE is the approved
-- last_activity_at backfill (existing timestamps only). The only DROPs are the
-- two permissive SELECT *policies* on the thread tables, which are replaced by
-- participant-scoped policies (restored verbatim by the rollback).
-- ============================================================================

begin;

-- ----------------------------------------------------------------------------
-- 1. Link business users to Supabase Auth identities
--    sub (uuid) from the JWT resolves to users.id via this column.
--    Kept as a plain uuid (unique) to avoid a cross-schema dependency on
--    auth.users. Optional tighter variant (uncomment if desired):
--      references auth.users (id) on delete set null
-- ----------------------------------------------------------------------------
alter table public.users
    add column if not exists auth_user_id uuid unique;

-- ----------------------------------------------------------------------------
-- 2. Reuse clarification threads for internal messages
--    kind='clarification' preserves existing routing behavior and rows.
--    kind='message'      is a freeform internal message thread.
-- ----------------------------------------------------------------------------
alter table public.clarification_requests
    add column if not exists kind text not null default 'clarification',
    add column if not exists subject text,
    add column if not exists last_activity_at timestamptz not null default now();

do $$
begin
    if not exists (
        select 1 from pg_constraint
        where conname = 'clarification_requests_kind_check'
    ) then
        alter table public.clarification_requests
            add constraint clarification_requests_kind_check
            check (kind in ('clarification', 'message'));
    end if;
end $$;

create index if not exists clarification_requests_kind_idx
    on public.clarification_requests (kind);

create index if not exists clarification_requests_last_activity_idx
    on public.clarification_requests (last_activity_at desc);

-- ----------------------------------------------------------------------------
-- 3. Per-user read receipts
--    Inbox unread = replies in my threads with no message_reads row for me.
-- ----------------------------------------------------------------------------
create table if not exists public.message_reads (
    id        bigint generated by default as identity primary key,
    reply_id  bigint not null references public.clarification_replies (id) on delete cascade,
    user_id   bigint not null references public.users (id) on delete cascade,
    read_at   timestamptz not null default now(),
    unique (reply_id, user_id)
);

create index if not exists message_reads_user_id_idx
    on public.message_reads (user_id);

create index if not exists message_reads_reply_id_idx
    on public.message_reads (reply_id);

-- ----------------------------------------------------------------------------
-- 4. Internal notifications (in-app substitute for external email)
-- ----------------------------------------------------------------------------
create table if not exists public.internal_notifications (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references public.users (id) on delete cascade,
    kind       text not null,          -- new_message | thread_reply | thread_assigned | thread_resolved | incident_escalated
    title      text not null,
    body       text,
    link_kind  text,                   -- thread | incident | policy
    link_id    bigint,
    read_at    timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists internal_notifications_user_idx
    on public.internal_notifications (user_id, read_at);

create index if not exists internal_notifications_created_idx
    on public.internal_notifications (created_at desc);

-- ----------------------------------------------------------------------------
-- 5. Auth-aware helper + Row Level Security
--    current_user_id() maps auth.uid() -> public.users.id.
--    The backend service role bypasses RLS as today; these policies are the
--    enforcement layer for direct/anon clients and a defense-in-depth backstop.
-- ----------------------------------------------------------------------------
create or replace function public.current_user_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
    select u.id
    from public.users u
    where u.auth_user_id = auth.uid()
    limit 1
$$;

alter table public.message_reads enable row level security;
alter table public.internal_notifications enable row level security;

-- IMPORTANT (live finding): every table today has one permissive policy,
--   <table>_select_authenticated FOR SELECT TO authenticated USING (true),
-- and RLS permissive policies are OR-ed. Merely ADDING a participant policy
-- would leave all authenticated users able to read every thread, so the
-- permissive read policies on the two thread tables are REPLACED here.
-- The rollback recreates the originals verbatim.
drop policy if exists clarification_requests_select_authenticated on public.clarification_requests;
drop policy if exists clarification_replies_select_authenticated on public.clarification_replies;

-- message_reads: strictly self-scoped
drop policy if exists message_reads_select_self on public.message_reads;
create policy message_reads_select_self on public.message_reads
    for select to authenticated
    using (user_id = public.current_user_id());

drop policy if exists message_reads_insert_self on public.message_reads;
create policy message_reads_insert_self on public.message_reads
    for insert to authenticated
    with check (user_id = public.current_user_id());

-- internal_notifications: recipient self-scoped
drop policy if exists internal_notifications_select_self on public.internal_notifications;
create policy internal_notifications_select_self on public.internal_notifications
    for select to authenticated
    using (user_id = public.current_user_id());

drop policy if exists internal_notifications_update_self on public.internal_notifications;
create policy internal_notifications_update_self on public.internal_notifications
    for update to authenticated
    using (user_id = public.current_user_id())
    with check (user_id = public.current_user_id());

-- clarification_requests: participants only (requester or assignee)
drop policy if exists clarification_requests_select_participant on public.clarification_requests;
create policy clarification_requests_select_participant on public.clarification_requests
    for select to authenticated
    using (
        user_id = public.current_user_id()
        or assigned_to = public.current_user_id()
    );

drop policy if exists clarification_requests_insert_self on public.clarification_requests;
create policy clarification_requests_insert_self on public.clarification_requests
    for insert to authenticated
    with check (user_id = public.current_user_id());

drop policy if exists clarification_requests_update_participant on public.clarification_requests;
create policy clarification_requests_update_participant on public.clarification_requests
    for update to authenticated
    using (
        user_id = public.current_user_id()
        or assigned_to = public.current_user_id()
    )
    with check (
        user_id = public.current_user_id()
        or assigned_to = public.current_user_id()
    );

-- clarification_replies: participants of the parent thread only
drop policy if exists clarification_replies_select_participant on public.clarification_replies;
create policy clarification_replies_select_participant on public.clarification_replies
    for select to authenticated
    using (
        exists (
            select 1
            from public.clarification_requests cr
            where cr.id = clarification_replies.request_id
              and (cr.user_id = public.current_user_id()
                   or cr.assigned_to = public.current_user_id())
        )
    );

drop policy if exists clarification_replies_insert_participant on public.clarification_replies;
create policy clarification_replies_insert_participant on public.clarification_replies
    for insert to authenticated
    with check (
        sender_id = public.current_user_id()
        and exists (
            select 1
            from public.clarification_requests cr
            where cr.id = clarification_replies.request_id
              and (cr.user_id = public.current_user_id()
                   or cr.assigned_to = public.current_user_id())
        )
    );

-- ----------------------------------------------------------------------------
-- 6. Backfill last_activity_at  — DECIDED: YES (Kiona)
--    Uses existing request/reply timestamps only:
--      greatest(request.created_at, latest reply.created_at)
--    Live scope: 33 requests, 1 reply, only 1 thread has a reply, so this
--    updates exactly that one row. Idempotent; touches only threads with replies.
-- ----------------------------------------------------------------------------
update public.clarification_requests cr
set last_activity_at = greatest(
        cr.created_at,
        coalesce(
            (select max(r.created_at)
             from public.clarification_replies r
             where r.request_id = cr.id),
            cr.created_at
        )
    )
where exists (
    select 1 from public.clarification_replies r where r.request_id = cr.id
);

commit;

